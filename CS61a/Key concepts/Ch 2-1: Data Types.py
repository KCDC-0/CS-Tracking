#### Intro to Building Abstractions with Data

# In Python, every value has a class (type) that defines its behavior
# Native (or bult in) data types share 2 primary characteristics:
# Literals: Expressions that evaluate directly to values of that type (e.g., 12)
# Built-in Operators: Functions and symbols (like + or *) designed to manipulate those values


# As an example of this, python supports 3 main numeric types:

# int (Integers): Represented exactly without size limits or approximation errors.
a = 12

# float (Real Numbers): Represented using "floating point" values.
b = 1.3

# complex (Complex Numbers): For values involving imaginary components (e.g., 1+1j).
c = 1+1j

# Other data types include non-numeric, built-in types as booleans (True/False),
# and other custom types created using the techniques of combination and abstraction,
# used for more complex values


## These are the main native data types in python:
# Booleans are either True or False.
# Numbers can be integers (1 and 2), floats (1.1 and 1.2), fractions (1/2 and 2/3), or even complex numbers.
# Strings are sequences of Unicode characters, e.g. an HTML document.
# Bytes and byte arrays, e.g. a JPEG image file.
# Lists are ordered sequences of values.
# Tuples are ordered, immutable sequences of values.
# Sets are unordered bags of values.
# Dictionaries are unordered bags of key-value pairs. 